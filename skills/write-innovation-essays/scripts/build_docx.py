from docx.enum.table import WD_TABLE_ALIGNMENT, WD_CELL_VERTICAL_ALIGNMENT
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Cm, Pt, RGBColor
from docx.opc.constants import RELATIONSHIP_TYPE as RT
from PIL import Image

DEFAULTS = dict(page_width_cm=21, page_height_cm=29.7, margin_cm=2.5,
    font="Times New Roman", body_pt=12, title_pt=16, heading_pt=12,
    line_spacing=1.5, paragraph_after_pt=0, first_line_cm=1,
    table_pt=10, table_header_fill="E8EFEA", table_border="D9D9D9",
    caption_pt=12, language="id", references_heading="Daftar Pustaka",
    appendices_heading="Daftar Lampiran", appendix_label="Lampiran",
    return_label="Esai", index_label="Daftar lampiran",
    references_new_page=True, appendices_new_page=False, page_numbers=True)

def atomically_write(path: Path, raw: bytes):
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, name = tempfile.mkstemp(prefix=path.name+".", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(fd, "wb") as f: f.write(raw)
        if Path(name).read_bytes() != raw: raise OSError("Temporary byte comparison failed")
        os.replace(name, path)
    finally:
        if os.path.exists(name): os.unlink(name)

def save_docx(document, path):
    buf = io.BytesIO(); document.save(buf); raw = buf.getvalue()
    with zipfile.ZipFile(io.BytesIO(raw)) as z:
        if z.testzip(): raise ValueError("DOCX ZIP integrity check failed")
    atomically_write(Path(path), raw)

def xmlval(parent, tag, val):
    el=OxmlElement(tag); el.set(qn("w:val"),str(val)); parent.append(el); return el

class Builder:
    def __init__(self, project: dict, base: Path):
        self.project=project; self.base=base
        self.c={**DEFAULTS, **project.get("format",{})}
        self.doc=Document(str(self.resolve(project["template"]))) if project.get("template") else Document()
        body=self.doc._element.body
        for el in list(body):
            if el.tag!=qn("w:sectPr"): body.remove(el)
        # Template is style input only: remove old content and its relationships.
        keep={"styles","stylesWithEffects","settings","webSettings","fontTable","theme","numbering"}
        for rid,rel in list(self.doc.part.rels.items()):
            if rel.reltype.rsplit("/",1)[-1] not in keep: self.doc.part.drop_rel(rid)
        for el in list(body.sectPr):
            if el.tag in [qn("w:headerReference"),qn("w:footerReference")]: body.sectPr.remove(el)
        for rid,rel in list(self.doc.part.package.rels.items()):
            if rel.reltype.endswith("custom-properties"): self.doc.part.package.rels.pop(rid)
        self.targets=set(); self.links=[]; self.bookmark=0; self.images=[]
        self.format_styles(); self.format_section(self.doc.sections[0]); self.configure_header_footer(self.doc.sections[0])

    def resolve(self, value):
        path=Path(value); return path if path.is_absolute() else self.base/path

    def format_styles(self):
        c=self.c
        for st in self.doc.styles:
            if st.type!=1: continue
            st.font.name=c["font"]; st.font.size=Pt(c["body_pt"]); st.font.color.rgb=RGBColor(0,0,0)
            pf=st.paragraph_format; pf.space_before=Pt(0); pf.space_after=Pt(c["paragraph_after_pt"]); pf.line_spacing=c["line_spacing"]
            for el in list(st.element.xpath("./w:pPr/w:pBdr")): el.getparent().remove(el)
        normal=self.doc.styles["Normal"]; normal.paragraph_format.alignment=WD_ALIGN_PARAGRAPH.JUSTIFY; normal.paragraph_format.first_line_indent=Cm(c["first_line_cm"])
        for n in ["Heading 1","Heading 2","Heading 3"]:
            st=self.doc.styles[n]; st.font.size=Pt(c["heading_pt"]); st.font.bold=True
            st.paragraph_format.first_line_indent=Cm(0); st.paragraph_format.keep_with_next=True; st.paragraph_format.space_before=Pt(6)
        st=self.doc.styles["Title"]; st.font.bold=True; st.font.size=Pt(c["title_pt"])
        st.paragraph_format.first_line_indent=Cm(0); st.paragraph_format.line_spacing=1.15; st.paragraph_format.space_after=Pt(5)

    def format_section(self, sec):
        c=self.c; sec.page_width=Cm(c["page_width_cm"]); sec.page_height=Cm(c["page_height_cm"])
        margins=c.get("margins_cm",{})
        for edge in ["top","bottom","left","right"]: setattr(sec,edge+"_margin",Cm(margins.get(edge,c["margin_cm"])))
        sec.header_distance=Cm(c.get("header_distance_cm",.7)); sec.footer_distance=Cm(c.get("footer_distance_cm",1))

    @property
    def width(self):
        s=self.doc.sections[-1]; return (s.page_width-s.left_margin-s.right_margin)/360000

    def configure_header_footer(self,sec):
        for hf in [sec.header,sec.footer,sec.first_page_header,sec.first_page_footer]:
            for el in list(hf._element): hf._element.remove(el)
        logos=self.project.get("header",{}).get("logos",[])
        if logos:
            t=sec.header.add_table(rows=1,cols=len(logos),width=Cm(self.width)); t.autofit=False
            for i,item in enumerate(logos):
                t.columns[i].width=Cm(self.width/len(logos)); p=t.cell(0,i).paragraphs[0]
                p.paragraph_format.first_line_indent=Cm(0);p.paragraph_format.line_spacing=1
                p.alignment=WD_ALIGN_PARAGRAPH.LEFT if i==0 else WD_ALIGN_PARAGRAPH.RIGHT
                p.add_run().add_picture(str(self.resolve(item["path"])),height=Cm(item.get("height_cm",.65)))
        if self.c["page_numbers"]:
            p=sec.footer.add_paragraph(); p.alignment=WD_ALIGN_PARAGRAPH.CENTER; p.paragraph_format.first_line_indent=Cm(0);p.paragraph_format.line_spacing=1
            field=OxmlElement("w:fldSimple");field.set(qn("w:instr"),"PAGE");p._p.append(field)

    @staticmethod
    def key(key):
        key=str(key);safe=re.sub(r"[^a-zA-Z0-9_]","_",key)
        if len(safe)>36:safe=safe[:26]+"_"+hashlib.sha256(key.encode()).hexdigest()[:8]
        return "es_"+safe

    def anchor(self,p,key):
        name=self.key(key)
        if name in self.targets: raise ValueError(f"Duplicate bookmark {key!r}")
        self.targets.add(name);self.bookmark+=1
        start=OxmlElement("w:bookmarkStart");start.set(qn("w:id"),str(self.bookmark));start.set(qn("w:name"),name)
        end=OxmlElement("w:bookmarkEnd");end.set(qn("w:id"),str(self.bookmark))
        p._p.insert(0,start);p._p.append(end)

    def link(self,p,label,target=None,url=None,size=None):
        h=OxmlElement("w:hyperlink")
        if target is not None:
            name=self.key(target); h.set(qn("w:anchor"),name);self.links.append(name)
        elif url:
            h.set(qn("r:id"),self.doc.part.relate_to(url,RT.HYPERLINK,is_external=True))
        else: raise ValueError("Hyperlink requires target or url")
        r=OxmlElement("w:r");pr=OxmlElement("w:rPr")
        fonts=OxmlElement("w:rFonts");fonts.set(qn("w:ascii"),self.c["font"]);fonts.set(qn("w:hAnsi"),self.c["font"]);pr.append(fonts)
        xmlval(pr,"w:color","000000");xmlval(pr,"w:sz",int((size or self.c["body_pt"])*2));xmlval(pr,"w:u","single");pr.append(OxmlElement("w:b"))
        r.append(pr);tx=OxmlElement("w:t");tx.set(qn("xml:space"),"preserve");tx.text=label;r.append(tx);h.append(r);p._p.append(h)

    def text(self,p,value,size=None,auto_links=True):
        if isinstance(value,list):
            for span in value:
                if "target" in span or "url" in span: self.link(p,span["text"],span.get("target"),span.get("url"),size)
                else:
                    r=p.add_run(span.get("text",""));r.bold=span.get("bold",False);r.italic=span.get("italic",False)
                    r.font.size=Pt(size or self.c["body_pt"]);r.font.name=self.c["font"];r.font.color.rgb=RGBColor(0,0,0)
            return
        text=str(value);last=0
        if not auto_links:
            r=p.add_run(text);r.font.size=Pt(size or self.c["body_pt"]);r.font.name=self.c["font"];r.font.color.rgb=RGBColor(0,0,0);return
        pattern=r"\b(?:Lampiran|Appendix)\s+([A-Z]+\.\d+)\b"
        for m in re.finditer(pattern,text):
            r=p.add_run(text[last:m.start()]);r.font.size=Pt(size or self.c["body_pt"])
            self.link(p,m.group(),m.group(1),size=size);last=m.end()
        r=p.add_run(text[last:]);r.font.size=Pt(size or self.c["body_pt"]);r.font.name=self.c["font"];r.font.color.rgb=RGBColor(0,0,0)

    def p(self,value="",*,indent=False,style=None,size=None,align=None,keep=False,auto_links=True):
        p=self.doc.add_paragraph(style=style);pf=p.paragraph_format
        pf.first_line_indent=Cm(self.c["first_line_cm"] if indent else 0);pf.keep_with_next=keep;pf.widow_control=True
        if align is not None:p.alignment=align
        self.text(p,value,size=size,auto_links=auto_links);return p

    def heading(self,title,key=None,level=1):
        p=self.p(title,style=f"Heading {level}",size=self.c["heading_pt"],auto_links=False)
        if key:self.anchor(p,key)
        return p

    def new_page(self,p): p.paragraph_format.page_break_before=True

    def table(self,b):
        headers=b["headers"];rows=b.get("rows",[]);n=len(headers)
        if not n or any(len(r)!=n for r in rows):raise ValueError("Table row length does not match headers")
        if b.get("title"):
            label=self.p(b["title"],keep=True);label.paragraph_format.line_spacing=1.15
            for r in label.runs:r.bold=True
        widths=b.get("widths_cm") or [self.width/n]*n
        if len(widths)!=n or any(float(w)<=0 for w in widths):raise ValueError("Invalid table widths")
        if sum(widths)>self.width+.02:raise ValueError(f"Table widths {sum(widths):.2f} cm exceed available {self.width:.2f} cm")
        t=self.doc.add_table(rows=1,cols=n);t.alignment=WD_TABLE_ALIGNMENT.CENTER;t.autofit=False
        for i,w in enumerate(widths):t.columns[i].width=Cm(w)
        props=t._tbl.tblPr;tw=props.find(qn("w:tblW"));tw.set(qn("w:type"),"dxa");tw.set(qn("w:w"),str(round(sum(widths)*567)))
        borders=OxmlElement("w:tblBorders")
        for edge in ["top","left","bottom","right","insideH","insideV"]:
            e=OxmlElement("w:"+edge);e.set(qn("w:val"),"single");e.set(qn("w:sz"),"3");e.set(qn("w:color"),self.c["table_border"]);borders.append(e)
        props.append(borders)
        mar=OxmlElement("w:tblCellMar")
        for edge,v in [("top",65),("bottom",65),("left",80),("right",80)]:
            e=OxmlElement("w:"+edge);e.set(qn("w:w"),str(v));e.set(qn("w:type"),"dxa");mar.append(e)
        props.append(mar)
        for ri,row in enumerate([headers]+rows):
            cells=t.rows[0].cells if ri==0 else t.add_row().cells
            trpr=cells[0]._tc.getparent().get_or_add_trPr();trpr.append(OxmlElement("w:cantSplit"))
            if ri==0:trpr.append(OxmlElement("w:tblHeader"))
            for i,v in enumerate(row):
                c=cells[i];c.width=Cm(widths[i]);c.vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER
                sh=OxmlElement("w:shd");sh.set(qn("w:fill"),self.c["table_header_fill"] if ri==0 else "FFFFFF");c._tc.get_or_add_tcPr().append(sh)
                p=c.paragraphs[0];pf=p.paragraph_format;pf.first_line_indent=Cm(0);pf.space_before=Pt(0);pf.space_after=Pt(0);pf.line_spacing=1
                value=v if isinstance(v,list)else""if v is None else str(v)
                display="".join(span.get("text","")for span in value)if isinstance(value,list)else value
                a=(b.get("alignments")or [None]*n)[i]
                if not a:
                    numeric=bool(re.fullmatch(r"(?:Rp|USD|IDR|\$)?\s*[−+\-]?\d[\d,. %/–—]*",display))
                    a="right"if numeric and ri else("left"if len(display)<70 else"justify")
                p.alignment={"left":WD_ALIGN_PARAGRAPH.LEFT,"right":WD_ALIGN_PARAGRAPH.RIGHT,"center":WD_ALIGN_PARAGRAPH.CENTER,"justify":WD_ALIGN_PARAGRAPH.JUSTIFY}[a]
                self.text(p,value,size=b.get("font_pt",self.c["table_pt"]))
                if ri==0:
                    for r in p.runs:r.bold=True
        if b.get("note"):
            for c in t.rows[-1].cells:
                for p in c.paragraphs:p.paragraph_format.keep_with_next=True
            cells=t.add_row().cells;c=cells[0].merge(cells[-1]);p=c.paragraphs[0]
            pf=p.paragraph_format;pf.first_line_indent=Cm(0);pf.space_before=Pt(0);pf.space_after=Pt(0);pf.line_spacing=1;pf.keep_together=True
            p.alignment=WD_ALIGN_PARAGRAPH.JUSTIFY;self.text(p,b["note"],size=b.get("font_pt",self.c["table_pt"]))
        return t

    def image(self,b,parent=None):
        path=self.resolve(b["path"])
        if not path.is_file():raise FileNotFoundError(path)
        with Image.open(path)as im:w,h=im.size
        width=min(b.get("width_cm",self.width),self.width)
        if b.get("max_height_cm"):width=min(width,b["max_height_cm"]*w/h)
        p=(parent.paragraphs[0] if parent else self.doc.add_paragraph());p.alignment=WD_ALIGN_PARAGRAPH.CENTER
        pf=p.paragraph_format;pf.first_line_indent=Cm(0);pf.line_spacing=1;pf.keep_with_next=bool(b.get("caption"));pf.space_after=Pt(0)
        p.add_run().add_picture(str(path),width=Cm(width))
        self.images.append({"path":str(path),"width_cm":width,"height_cm":width*h/w,"pixels":[w,h]})
        if b.get("caption"):
            cp=parent.add_paragraph()if parent else self.doc.add_paragraph();cp.alignment=WD_ALIGN_PARAGRAPH.CENTER;cp.paragraph_format.first_line_indent=Cm(0);cp.paragraph_format.line_spacing=1.1
            self.text(cp,b["caption"],size=self.c["caption_pt"])
        return p

    def block(self,b):
        kind=b.get("type","paragraph")
        if kind=="paragraph":
            p=self.p(b.get("runs",b.get("text","")),indent=b.get("indent",True))
            if b.get("id"):self.anchor(p,b["id"])
        elif kind=="heading":self.heading(b["text"],b.get("id"),b.get("level",1))
        elif kind=="table":self.table(b)
        elif kind=="image":self.image(b)
        elif kind=="image_pair":
            items=b["items"];widths=b.get("widths_cm",[self.width/len(items)]*len(items))
            if len(items)!=len(widths)or sum(widths)>self.width+.02:raise ValueError("Invalid image-pair widths")
            t=self.doc.add_table(rows=1,cols=len(items));t.autofit=False;t.alignment=WD_TABLE_ALIGNMENT.CENTER;t.rows[0]._tr.get_or_add_trPr().append(OxmlElement("w:cantSplit"))
            for i,item in enumerate(items):
                t.columns[i].width=Cm(widths[i]);t.cell(0,i).width=Cm(widths[i]);t.cell(0,i).vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.TOP
                self.image({**item,"width_cm":min(item.get("width_cm",widths[i]-.4),widths[i]-.4)},t.cell(0,i))
        elif kind=="qr":
            if not b.get("label")or not b.get("url"):raise ValueError("QR requires an honest label and URL")
            try:import qrcode
            except ImportError as e:raise RuntimeError("QR generation requires the optional qrcode package")from e
            if not hasattr(self,"_qr_dir"):self._qr_dir=tempfile.TemporaryDirectory(prefix="essay-qr-")
            path=Path(self._qr_dir.name)/f"qr-{len(self.images)}.png";qrcode.make(b["url"]).save(path)
            self.image({"path":str(path),"caption":b["label"],"width_cm":b.get("width_cm",3)})
            p=self.p(align=WD_ALIGN_PARAGRAPH.CENTER);self.link(p,b.get("visible_url",b["url"]),url=b["url"])
        elif kind=="page_break":self.doc.add_page_break()
        else:raise ValueError(f"Unknown block type {kind}")

    def build(self):
        cover=self.project.get("cover",{})
        if cover.get("enabled"):
            sec=self.doc.sections[0];sec.different_first_page_header_footer=True
            for _ in range(cover.get("top_blank_lines",4)):self.p("")
            for label in cover.get("lines",["[Essay title]","[Participant name]"]):self.p(label,align=WD_ALIGN_PARAGRAPH.CENTER)
            sec=self.doc.add_section(WD_SECTION_START.NEW_PAGE);sec.different_first_page_header_footer=False
            self.format_section(sec);pg=OxmlElement("w:pgNumType");pg.set(qn("w:start"),"1");sec._sectPr.append(pg)
        title=self.project["title"];p=self.p(title,style="Title",size=self.c["title_pt"],align=WD_ALIGN_PARAGRAPH.CENTER,auto_links=False);self.anchor(p,"essay")
        for b in self.project.get("body",[]):self.block(b)
        refs=self.project.get("references",[])
        if refs:
            p=self.heading(self.c["references_heading"],"references")
            if self.c["references_new_page"]:self.new_page(p)
            for ref in refs:
                p=self.p(ref.get("runs",ref.get("text",""))if isinstance(ref,dict)else ref,auto_links=False)
                pf=p.paragraph_format;pf.left_indent=Cm(.7);pf.first_line_indent=Cm(-.7);pf.keep_together=True;p.alignment=WD_ALIGN_PARAGRAPH.LEFT
        apps=self.project.get("appendices",[])
        if apps:
            def index():
                p=self.heading(self.c["appendices_heading"],"appendix_index")
                if self.c["appendices_new_page"]:self.new_page(p)
                for s in apps:
                    p=self.p(align=WD_ALIGN_PARAGRAPH.LEFT);self.link(p,f"{s['id']}  {s['title']}",s["id"]);p.paragraph_format.line_spacing=1.1
            def append(s):
                self.heading(f"{self.c['appendix_label']} {s['id']}. {s['title']}",s["id"])
                p=self.p(align=WD_ALIGN_PARAGRAPH.LEFT,keep=True);p.paragraph_format.line_spacing=1
                self.link(p,self.c["return_label"],s.get("return_to","essay"));p.add_run("  |  ");self.link(p,self.c["index_label"],"appendix_index")
                for b in s.get("blocks",[]):self.block(b)
            if self.project.get("appendix_index_position")=="after_first":
                append(apps[0]);index()
                for s in apps[1:]:append(s)
            else:
                index()
                for s in apps:append(s)
        missing=set(self.links)-self.targets
        if missing:raise ValueError("Unresolved internal hyperlink targets: "+", ".join(sorted(missing)))
        cp=self.doc.core_properties;cp.author="";cp.last_modified_by="";cp.comments="";cp.title=title
        cp.created=cp.modified=datetime.now(timezone.utc)
        return self.doc

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument("project",nargs="?",type=Path);parser.add_argument("--output",type=Path);parser.add_argument("--make-template",type=Path)
    args=parser.parse_args()
    if args.make_template:
        b=Builder({"title":"[Essay title]"},Path.cwd());save_docx(b.build(),args.make_template)
        print(json.dumps({"template":str(args.make_template),"status":"created"}));return
    if not args.project or not args.output:parser.error("project and --output are required")
    project=json.loads(args.project.read_text(encoding="utf-8"));b=Builder(project,args.project.resolve().parent);save_docx(b.build(),args.output)
    manifest={"docx":str(args.output),"bookmarks":len(b.targets),"internal_links":len(b.links),"unresolved_links":[],"images":b.images,"format":b.c,"body_start_text":project["title"],"body_end_before_text":b.c["references_heading"]if project.get("references")else b.c["appendices_heading"]if project.get("appendices")else None}
    atomically_write(args.output.with_suffix(".build.json"),json.dumps(manifest,ensure_ascii=False,indent=2).encode())
    print(json.dumps({"docx":str(args.output),"bookmarks":len(b.targets),"internal_links":len(b.links),"status":"built_not_visually_verified"}))

if __name__=="__main__":main()
