#!/usr/bin/env python3
"""Build an editable essay DOCX from a project JSON file.

python build_docx.py project.json --output essay.docx
python build_docx.py --make-template neutral_essay.docx

This is a formatter, not a fact checker. Project guidebook settings override the
defaults. No source, result, partnership or estimate is generated by this tool.
"""
